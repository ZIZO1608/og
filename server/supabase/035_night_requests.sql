-- =============================================================================
--  035 — NIGHT REQUESTS: the one thing that may be written while the shop is shut
-- -----------------------------------------------------------------------------
--  Run by hand in Supabase → SQL Editor, AFTER 030 and 031 (it grants to
--  og_vps, and uses schema erp). Safe to run twice: every statement replaces or
--  skips what is already there. No local migration goes with it and it creates
--  no mirrored table, so mirror-lag.js, drift, reconcile and restore do not
--  change.
--
--  WHAT NIGHT MODE IS
--    When the shop laptop is off or out of reach, og-bridge on the VPS serves
--    a small app at shop.ogsports1.com/night (vps/og-bridge/src/night.js). It
--    reads the mirror as og_vps — stock, customers, recent orders — and it may
--    write ONE thing: a REQUEST (a customer, some sizes, delivery or pickup).
--    The request waits here. The laptop collects it the next time it is on
--    (server/lib/requests.js, from Inbox.collect every minute) into a list
--    called "Waiting for the shop", where a PERSON accepts it — it becomes a
--    normal order through the laptop's own order code — or rejects it with a
--    reason. The decision is written back here so the night app can show it.
--    Nothing is applied by itself, and the laptop stays the only writer of
--    shop data.
--
--  WHY A TABLE OF ITS OWN, BESIDE og-track's inbox.items
--    inbox.items is taken, applied and marked done in one pass (a review, a
--    Notify me). A request is DECIDED BY A PERSON, later, and the answer has to
--    travel back: waiting → received → accepted | rejected. That is the shape
--    wip/web-orders gave web.orders, so this table is GENERIC on purpose
--    (source 'night' | 'web'): the website's orders can arrive here later and
--    land in the same list. og-track's table and functions are not touched.
--
--  WHAT og_vps GAINS — AND WHAT IT DOES NOT
--    EXECUTE on erp.request_submit and erp.requests_list. That is all.
--    NO table privilege anywhere (not even USAGE on schema inbox), so it is
--    still SELECT-only on the shop's tables. Its sessions stay read-only by
--    default (030); og-bridge opens `BEGIN READ WRITE` for the submit call and
--    for nothing else — an INSERT inside a SECURITY DEFINER function still
--    fails in a read-only transaction, which is the point of 030's default.
--    The last block of this file FAILS THE WHOLE FILE if og_vps can write to
--    any relation, or read inbox.requests directly.
--
--  WHAT IT CREATES
--    inbox.requests                        the requests (schema inbox: not exposed)
--    erp.request_submit(user, op, req)     og_vps       — a night user asks
--    erp.requests_list(user, limit)        og_vps       — what became of them
--    public.requests_take(lineage, limit)  service_role — the laptop collects
--    public.requests_mark(lineage, items)  service_role — received / accepted / rejected
--    inbox.req_*                           private helpers, no role may call them
--
--  LIMITS (a leaked night account must not be able to bury the shop)
--    20 lines, 20 of one size, 60 pieces per request · 5 undecided per phone ·
--    30 per night user per hour · 1,000 undecided in all · 8 KB per payload.
--
--  AFTER RUNNING IT
--    Do NOT add `inbox` or `erp` to Exposed schemas. The last two queries show
--    what og_vps can do; the guard above them has already refused a wrong one.
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS inbox;
REVOKE ALL ON SCHEMA inbox FROM PUBLIC;
DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon', 'authenticated', 'service_role', 'og_vps'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA inbox FROM %I', r);
    END IF;
  END LOOP;
END $$;

-- -----------------------------------------------------------------------------
--  The table. ref is what people read ("N-0042"); op is the requester's own
--  idempotency key, so a form sent twice on a slow line is one request.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS inbox.requests (
  id             bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref            text        NOT NULL,
  source         text        NOT NULL,
  op             text        NOT NULL,
  payload        jsonb       NOT NULL,
  phone_digits   text        NOT NULL,
  by_user        text,
  revision       integer     NOT NULL DEFAULT 1,
  state          text        NOT NULL DEFAULT 'waiting',
  state_code     text,
  state_note     text,
  sale_id        text,
  taken_by       text,
  taken_revision integer,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  decided_at     timestamptz,
  CONSTRAINT requests_ref_unique    UNIQUE (ref),
  CONSTRAINT requests_op_unique     UNIQUE (source, op),
  CONSTRAINT requests_ref_shape     CHECK (ref ~ '^[A-Za-z0-9][A-Za-z0-9_-]{2,39}$'),
  CONSTRAINT requests_source_check  CHECK (source IN ('night', 'web')),
  CONSTRAINT requests_state_check   CHECK (state IN ('waiting', 'received', 'accepted', 'rejected')),
  CONSTRAINT requests_code_shape    CHECK (state_code IS NULL OR state_code ~ '^[a-z_]{1,40}$'),
  CONSTRAINT requests_note_len      CHECK (state_note IS NULL OR char_length(state_note) <= 200),
  CONSTRAINT requests_sale_len      CHECK (sale_id IS NULL OR char_length(sale_id) <= 40),
  CONSTRAINT requests_payload_size  CHECK (octet_length(payload::text) <= 8192)
);

COMMENT ON TABLE inbox.requests IS
  'Night requests (and, later, website orders) waiting for the shop laptop to decide (035). Not a mirrored table; never add it to the POS sync, reconcile or restore lists.';

